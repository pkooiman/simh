/*  get a byte from memory */

uint8 get_mbyte(uint16 addr)
{
    uint8 val = 0;

    //If high address bit is set, it is for video which will do further decoding
    if (addr & AESVIDMEMMASK)
    {
        //sim_printf("Vidmem 0x%04X value %02X (%c)\n", addr, val, val);
        val = aes103vid_mem_from_cpu(addr, 0, val);

    }
    else
    {
        if (!aes103_bootromoff && addr >= AESBOOTROMBASE && addr < (AESBOOTROMBASE + AESBOOTROMSIZE))
        {
            val = aesbootrom[addr - AESBOOTROMBASE];
        }
        else if (addr >= AESRAMBASE && addr < (AESRAMBASE + AESRAMSIZE))
        {
            val = RAM_get_mbyte(addr);
        }
        else
        {
            sim_printf("Read from invalid address %04X\n", addr);
        }
    }
    return (val & BYTEMASK);
}

/*  put a byte into memory */

void put_mbyte(uint16 addr, uint8 val)
{
    //If high address bit is set, it is for video which will do further decoding
    if (addr & AESVIDMEMMASK)
    {
        //sim_printf("Vidmem 0x%04X value %02X (%c)\n", addr, val, val);
        aes103vid_mem_from_cpu(addr, 1, val);
    
    }
    else if (addr >= AESRAMBASE && addr < (AESRAMBASE + AESRAMSIZE))
    {
        //Writing to low ram is always possible, only reading is redirected to ROM on start
        //if (!(!aes103_bootromoff && addr >= AESBOOTROMBASE && addr < (AESBOOTROMBASE + AESBOOTROMSIZE)))
        RAM_put_mbyte(addr, val);
    }
    else
    {
        sim_printf("Write to invalid address %04X\n", addr);
    }
    
}

uint16 get_mword(uint32 addr)
{
    uint16 val;
    if (addr >= MAXMEMSIZE)
        return 0;
    val = get_mbyte(addr);
    val |= (get_mbyte(addr + 1) << 8);
    return val;
}


void put_mword(uint32 addr, uint16 val)
{
    put_mbyte(addr, val & 0xff);
    put_mbyte(addr + 1, val >> 8);
}




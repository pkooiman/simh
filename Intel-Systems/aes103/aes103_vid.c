t_stat aes103vid_svc(UNIT *uptr)
{
    SIM_KEY_EVENT kev;
    
    aes103vid_refresh();
    

    if (aes103vid_kb_callback != NULL) {
        if (vid_poll_kb(&kev) == SCPE_OK) {
            (*aes103vid_kb_callback)(&kev);
        }
    }

    sim_activate_after_abs(uptr, uptr->wait); // 25ms refresh rate

    return SCPE_OK;
}


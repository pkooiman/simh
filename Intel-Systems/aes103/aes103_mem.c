uint8 aes103mem_r0(t_bool io, uint8 data, uint8 devnum)
{
    if (io == 0)
    {
        //switches 0
        return aes103_switches0;
    }
    else
        return 0;
}

uint8 aes103mem_r1(t_bool io, uint8 data, uint8 devnum)
{
    if (io == 0)
    {
        //swicthes 1
        return aes103_switches1;
    }
    else
        return 0;
}

uint8 aes103mem_r3(t_bool io, uint8 data, uint8 devnum)
{
    if (io == 0)
    {
        //Map out boot rom on register read
        aes103_bootromoff = 1;
        sim_printf("Disable boot ROM\n");
        return 0;
    }
    else
        return 0;
}


t_stat aes103mem_reset (DEVICE *dptr)
{
    aes103_bootromoff = 0;
    aes103_switches0 = 0x0;
    aes103_switches1 = 1;
    RAM_cfg(AESRAMBASE, AESRAMSIZE, 0);
    
    return SCPE_OK;
}



